#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";

const root = path.resolve(import.meta.dirname, "..");
const read = (name) => fs.readFileSync(path.join(root, name), "utf8");
const compose = read("docker-compose.yml");
const block = (name) => compose.match(new RegExp(`^  ${name}:\\n[\\s\\S]*?(?=^  [A-Za-z0-9_-]+:|^volumes:|^secrets:|^networks:)`, "m"))?.[0] ?? "";
const app = block("app");
const prom = block("prometheus");
const grafana = block("grafana");
const node = block("node-exporter");
const tokenInitService = block("monitoring-secrets-init");
const api = read("apps/admin-api/src/app.ts");
const env = read("apps/admin-api/src/config/env.ts");
const metrics = read("apps/admin-api/src/services/prometheus.service.ts");
const registry = read("apps/admin-api/src/utils/prometheus-metrics.ts");
const repository = read("apps/admin-api/src/repositories/system.repository.ts");
const routes = read("apps/admin-api/src/routes/admin.routes.ts");
const schemas = read("apps/admin-api/src/validation/schemas.ts");
const eventTests = read("apps/admin-api/test/event-utils.test.js");
const html = read("apps/admin-ui/index.html");
const ui = read("apps/admin-ui/app.js");
const bootstrap = read("infrastructure/secrets/bootstrap.sh");
const tokenInit = read("infrastructure/monitoring/init-monitoring-secrets.sh");
const prometheusConfig = read("infrastructure/monitoring/prometheus.yml");
const grafanaDashboard = JSON.parse(read("infrastructure/monitoring/grafana/dashboards/mailcore-operations.json"));
const docs = read("docs/MILESTONE_07.md");
const packageJson = JSON.parse(read("apps/admin-api/package.json"));

assert.match(compose, /^  prometheus:/m);
assert.match(compose, /^  grafana:/m);
assert.match(compose, /^  node-exporter:/m);
assert.match(app, /monitoringnet/);
assert.match(app, /PROMETHEUS_SCRAPE_TOKEN_FILE: \/run\/mailcore-secrets\/prometheus_scrape_token/);
assert.match(app, /mailcore_monitoring_secrets:\/run\/mailcore-secrets:ro/);
assert.match(prom, /mailcore_monitoring_secrets:\/run\/mailcore-secrets:ro/);
assert.match(tokenInitService, /mailcore_monitoring_secrets:\/run\/mailcore-secrets/);
assert.match(tokenInitService, /network_mode: none/);
assert.match(tokenInitService, /DAC_READ_SEARCH/);
assert.match(tokenInitService, /restart: "no"/);
assert.match(app, /monitoring-secrets-init:\n\s+condition: service_completed_successfully/);
assert.match(prom, /monitoring-secrets-init:\n\s+condition: service_completed_successfully/);
assert.match(compose, /mailcore_monitoring_secrets:/);
assert.doesNotMatch(compose, /file: \.\/secrets\/runtime\/prometheus_scrape_token/);
assert.doesNotMatch(compose, /file: \.\/secrets\/runtime\/grafana_admin_password/);
assert.match(tokenInit, /head -c 48 \/dev\/urandom/);
assert.match(tokenInit, /generate_secret grafana_admin_password/);
assert.match(tokenInit, /LEGACY_DIR/);
assert.match(tokenInit, /chmod 0444/);
assert.match(tokenInit, /preserving existing \$\{?name\}? in Docker volume/);
assert.match(prom, /127\.0\.0\.1|PROMETHEUS_BIND_ADDRESS/);
assert.match(grafana, /GF_SECURITY_ADMIN_PASSWORD__FILE: \/run\/mailcore-secrets\/grafana_admin_password/);
assert.match(grafana, /mailcore_monitoring_secrets:\/run\/mailcore-secrets:ro/);
assert.match(grafana, /monitoring-secrets-init:\n\s+condition: service_completed_successfully/);
assert.doesNotMatch(grafana, /\n    secrets:\n/);
assert.match(grafana, /127\.0\.0\.1|GRAFANA_BIND_ADDRESS/);
assert.match(node, /\/:\/host:ro,rslave/);
assert.match(compose, /monitoringnet:\n    driver: bridge\n    internal: true/);
assert.doesNotMatch(bootstrap, /persist\("prometheus_scrape_token"/);
assert.match(env, /readSecret\("PROMETHEUS_SCRAPE_TOKEN"\)/);
assert.match(env, /PROMETHEUS_SCRAPE_TOKEN_FILE must contain at least 32 characters/);
assert.match(packageJson.scripts.test, /PROMETHEUS_SCRAPE_TOKEN=TEST_ONLY_/);
assert.match(api, /timingSafeEqual/);
assert.match(api, /req\.get\("authorization"\)/);
assert.match(api, /renderPrometheusMetrics/);
assert.match(registry, /mailcore_http_requests_total/);
assert.match(registry, /mailcore_http_request_duration_seconds_bucket/);
assert.match(metrics, /mailcore_postgres_pool_connections/);
assert.match(metrics, /mailcore_postgres_database_stats/);
assert.match(metrics, /mailcore_postfix_queue_messages/);
assert.match(repository, /async getMailAnalytics\(days: number\)/);
assert.match(repository, /mail\.delivery\.accepted/);
assert.match(repository, /mail\.delivery\.deferred/);
assert.match(repository, /mail\.delivery\.bounced/);
assert.match(repository, /terminalDeliverySuccessRate/);
assert.match(routes, /adminRouter\.get\("\/analytics\/mail", requireRoles\("admin"\)/);
assert.match(schemas, /mailAnalyticsQuerySchema.*max\(90\)/);
assert.match(schemas, /z\.union\(\[z\.boolean\(\), z\.enum\(\["true", "false"\]\)/);
assert.match(eventTests, /unreadOnly: true/);
assert.match(eventTests, /unreadOnly: false/);
assert.match(html, /mail-flow-analytics-card/);
assert.match(ui, /renderMailFlowAnalytics/);
assert.match(prometheusConfig, /bearer_token_file: \/run\/mailcore-secrets\/prometheus_scrape_token/);
assert.match(prometheusConfig, /node-exporter:9100/);
assert.ok(grafanaDashboard.panels.some((panel) => panel.title === "Postfix queue depth"));
assert.ok(grafanaDashboard.panels.some((panel) => panel.title === "Host CPU utilization"));
assert.match(docs, /named Docker volume/i);
assert.match(docs, /SSH tunnel/i);
assert.match(docs, /accepted by the remote SMTP server/i);

console.log("Milestone 07 static checks passed: named-volume token initialization, boolean/string query compatibility, authenticated Prometheus metrics, loopback-only monitoring, mail analytics and operational dashboards.");
